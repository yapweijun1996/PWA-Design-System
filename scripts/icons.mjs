import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function validateIconRegistry(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value) || Object.keys(value).sort().join(',') !== 'icons,version' || value.version !== 1 || !Array.isArray(value.icons) || !value.icons.length || value.icons.length > 100) throw new Error('Invalid approved icon registry');
  const names = new Set(), glyphs = new Set();
  let previous = '';
  for (const item of value.icons) {
    if (!item || typeof item !== 'object' || Array.isArray(item) || Object.keys(item).sort().join(',') !== 'description,glyph,name' || typeof item.name !== 'string' || !/^[a-z]+(?:-[a-z]+)*$/.test(item.name) || ['constructor', 'prototype'].includes(item.name) || item.name.length > 40 || typeof item.glyph !== 'string' || [...item.glyph].length !== 1 || /[\s\p{Cc}\p{Cf}\p{Cs}\p{M}<>]/u.test(item.glyph) || typeof item.description !== 'string' || !item.description.trim() || item.description.length > 160 || /[\p{Cc}]/u.test(item.description)) throw new Error('Invalid approved icon');
    if (names.has(item.name) || glyphs.has(item.glyph)) throw new Error('Duplicate approved icon name or glyph');
    if (previous && item.name <= previous) throw new Error('Approved icons must be sorted by name');
    names.add(item.name); glyphs.add(item.glyph); previous = item.name;
  }
  return value;
}

export async function readIconRegistry() {
  const text = await readFile(resolve(root, 'packages/icons/approved-icons.json'), 'utf8');
  if (Buffer.byteLength(text) > 16384) throw new Error('Approved icon registry exceeds 16 KiB');
  return validateIconRegistry(JSON.parse(text));
}

export async function generateIcons(check = false) {
  const registry = await readIconRegistry();
  const glyphs = Object.fromEntries(registry.icons.map(item => [item.name, item.glyph]));
  const js = `// Generated by scripts/icons.mjs. Do not edit.\nexport const approvedIcons = Object.freeze(${JSON.stringify(glyphs, null, 2)});\nexport function isApprovedIcon(name) { return typeof name === 'string' && Object.hasOwn(approvedIcons, name); }\nexport function getIcon(name) { if (!isApprovedIcon(name)) throw new TypeError('Unknown approved icon'); return approvedIcons[name]; }\n`;
  const names = registry.icons.map(item => JSON.stringify(item.name)).join(' | ');
  const types = `// Generated by scripts/icons.mjs. Do not edit.\nexport type IconName = ${names};\nexport declare const approvedIcons: Readonly<Record<IconName, string>>;\nexport declare function isApprovedIcon(name: unknown): name is IconName;\nexport declare function getIcon(name: IconName): string;\n`;
  const directory = resolve(root, 'packages/icons/generated');
  if (!check) await mkdir(directory, { recursive: true });
  for (const [name, content] of [['index.js', js], ['index.d.ts', types]]) {
    const path = resolve(directory, name);
    if (check) { if (await readFile(path, 'utf8').catch(() => '') !== content) throw new Error(`Approved icon output is stale: ${name}`); }
    else await writeFile(path, content);
  }
  return registry;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length && args[0] !== '--check')) { console.error('Usage: node scripts/icons.mjs [--check]'); process.exitCode = 1; }
  else generateIcons(args[0] === '--check').then(() => console.log('Approved icon outputs are current.')).catch(error => { console.error(error.message); process.exitCode = 1; });
}
