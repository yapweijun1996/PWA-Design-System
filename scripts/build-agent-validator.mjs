import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export async function buildAgentValidator(check = false, { read = readFile, write = writeFile } = {}) {
  const schema = JSON.parse(await read(resolve(root, 'packages/agent-contract/design-system.schema.json'), 'utf8'));
  const ajv = new Ajv({ strict: true, allErrors: true, ownProperties: true, code: { source: true, esm: true } });
  const generated = standaloneCode(ajv, ajv.compile(schema));
  const helper = 'require("ajv/dist/runtime/ucs2length").default';
  if (!generated.includes(helper)) throw new Error('Unexpected standalone validator helper');
  const esm = generated.replaceAll(helper, 'agentUnicodeLength');
  if (/\b(?:require\s*\(|eval\s*\(|new\s+Function\b)/.test(esm)) throw new Error('Standalone validator has unexpected runtime code generation or require');
  const license = `${(await read(resolve(root, 'packages/agent-contract/AJV-LICENSE.txt'), 'utf8')).trimEnd()}\n`;
  const installedLicense = `${(await read(resolve(root, 'node_modules/ajv/LICENSE'), 'utf8')).trimEnd()}\n`;
  if (license !== installedLicense || license.includes('*/')) throw new Error('Ajv license attribution is missing or stale');
  // String iteration counts surrogate pairs as one code point, matching JSON Schema length semantics.
  const code = `/*!\nGenerated by scripts/build-agent-validator.mjs from the trusted schema. Do not edit.\nAjv attribution:\n${license}\n*/\nconst agentUnicodeLength = value => [...value].length;\n${esm}`;
  const path = resolve(root, 'packages/agent-contract/generated-validator.mjs');
  if (check) { const existing = await read(path, 'utf8').catch(() => ''); if (existing !== code) throw new Error('Agent validator is stale'); }
  else await write(path, code);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length && args[0] !== '--check')) { console.error('Usage: node scripts/build-agent-validator.mjs [--check]'); process.exitCode = 1; }
  else buildAgentValidator(args[0] === '--check').then(() => console.log('Agent validator is current.')).catch(error => { console.error(error.message); process.exitCode = 1; });
}
